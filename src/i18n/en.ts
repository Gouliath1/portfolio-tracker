/**
 * English catalog — the source of truth for the UI's key set.
 *
 * Flat keys, dot-namespaced by feature. Flat (rather than nested) keeps the
 * `TranslationKey` union cheap for the compiler, makes a locale file trivially
 * diffable against this one, and means adding a string is a two-file change
 * that TypeScript enforces.
 *
 * Conventions:
 *  - `{placeholder}` slots are substituted at render time; every locale must
 *    keep the same placeholder names (the values are numbers, dates, tickers).
 *  - `…Before` / `…After` pairs wrap a piece of markup or user data that sits
 *    inside a sentence, so a locale can move it to wherever its grammar wants.
 *  - `err…` keys are validation and failure messages.
 *  - Ticker symbols, company names, sector names, broker names and account
 *    names are data, not UI text, and are never translated.
 */
